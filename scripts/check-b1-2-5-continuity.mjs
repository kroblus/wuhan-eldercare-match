const visit = initial.flows.find(f => f.state === 'visit_simulated')
const constructEvaluation = async visitId => {
  // Each invocation gets a new Page instance, as navigating away and back does.
  load('pages/visit/evaluation')
  const p = { ...page, data: structuredClone(page.data), setData(patch) { Object.assign(this.data, patch) } }
  await p.onLoad({ visitId })
  return p
}
const evaluation = await constructEvaluation(visit.visitId)
assert.equal(evaluation.data.pageState, 'editing')
assert.equal(evaluation.data.draft.overallRating, null)
evaluation.onNextStep(); assert.equal(evaluation.data.step, 1)
assert.ok(evaluation.data.overallRatingValidationMessage)
const event = dataset => ({ currentTarget: { dataset } })
evaluation.onRatingTap(event({ question: 'overallRating', value: 5 }))
evaluation.onConsiderationTap(event({ value: 'willing' }))
evaluation.onNextStep(); assert.equal(evaluation.data.step, 2)
const dimensions = evaluation.data.ratingSections.flatMap(s => s.items)
assert.equal(dimensions.length, 21)
for (const item of dimensions) evaluation.onRatingTap(event({ question: item.key, value: 3 }))
evaluation.onFeeClarityTap(event({ value: 'clear' }))
for (const topic of evaluation.data.feeTopicExplanations) evaluation.onFeeTopicTap(event({ topic: topic.key, value: 'unconfirmed' }))
